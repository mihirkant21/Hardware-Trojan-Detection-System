// ============================================================
// Module: alu_16bit_instrumented
// Description: Special simulation harness for dataset generation.
//              Wraps all 4 variants (clean + 3 trojans) and
//              exposes internal switching signals for VCD parsing.
//              Controlled via $readmemh stimulus from Python.
// ============================================================
`timescale 1ns / 1ps

module alu_dataset_harness;

    // ── Clock & Reset ─────────────────────────────────────────
    reg clk, rst;
    always #5 clk = ~clk;

    // ── Stimulus inputs ───────────────────────────────────────
    reg  [15:0] A, B;
    reg  [3:0]  opcode;

    // ── Clean ALU outputs ─────────────────────────────────────
    wire [15:0] clean_result;
    wire        clean_Z, clean_C, clean_V, clean_S;

    // ── Trojan 1 outputs ──────────────────────────────────────
    wire [15:0] t1_result;
    wire        t1_Z, t1_C, t1_V, t1_S;

    // ── Trojan 2 outputs ──────────────────────────────────────
    wire [15:0] t2_result;
    wire        t2_Z, t2_C, t2_V, t2_S;

    // ── Trojan 3 outputs + leakage ────────────────────────────
    wire [15:0] t3_result;
    wire        t3_Z, t3_C, t3_V, t3_S;
    wire [7:0]  t3_leakage;

    // ── DUT Instantiations ────────────────────────────────────
    alu_16bit CLEAN (
        .A(A), .B(B), .opcode(opcode),
        .result(clean_result),
        .Z(clean_Z), .C(clean_C), .V(clean_V), .S(clean_S)
    );

    trojan1_flag_tamper T1 (
        .A(A), .B(B), .opcode(opcode),
        .result(t1_result),
        .Z(t1_Z), .C(t1_C), .V(t1_V), .S(t1_S)
    );

    trojan2_counter_payload T2 (
        .clk(clk), .rst(rst),
        .A(A), .B(B), .opcode(opcode),
        .result(t2_result),
        .Z(t2_Z), .C(t2_C), .V(t2_V), .S(t2_S)
    );

    trojan3_sidechannel T3 (
        .clk(clk), .rst(rst),
        .A(A), .B(B), .opcode(opcode),
        .result(t3_result),
        .Z(t3_Z), .C(t3_C), .V(t3_V), .S(t3_S),
        .leakage_activity(t3_leakage)
    );

    // ── Parameters ───────────────────────────────────────────
    parameter NUM_CYCLES = 10500;

    // ── Stimulus arrays ───────────────────────────────────────
    reg [15:0] stim_A      [0:NUM_CYCLES-1];
    reg [15:0] stim_B      [0:NUM_CYCLES-1];
    reg [3:0]  stim_op     [0:NUM_CYCLES-1];
    reg [1:0]  stim_label  [0:NUM_CYCLES-1]; // 0=clean,1=T1,2=T2,3=T3

    // ── Result log file ───────────────────────────────────────
    integer fd;
    integer i;

    // ── Previous signal values for toggle counting ────────────
    reg [15:0] prev_clean_result, prev_t1_result, prev_t2_result, prev_t3_result;
    reg [7:0]  prev_leakage;
    reg [3:0]  prev_flags;

    // ── Toggle count registers ────────────────────────────────
    integer clean_toggles, t1_toggles, t2_toggles, t3_toggles;
    integer leakage_toggles;
    integer flag_toggles;

    // ── Manual popcount function (iverilog v12 compatible) ────
    function integer popcount16;
        input [15:0] v;
        integer k, cnt;
        begin
            cnt = 0;
            for (k = 0; k < 16; k = k + 1)
                if (v[k]) cnt = cnt + 1;
            popcount16 = cnt;
        end
    endfunction

    function integer popcount8;
        input [7:0] v;
        integer k, cnt;
        begin
            cnt = 0;
            for (k = 0; k < 8; k = k + 1)
                if (v[k]) cnt = cnt + 1;
            popcount8 = cnt;
        end
    endfunction

    function integer popcount4;
        input [3:0] v;
        integer k, cnt;
        begin
            cnt = 0;
            for (k = 0; k < 4; k = k + 1)
                if (v[k]) cnt = cnt + 1;
            popcount4 = cnt;
        end
    endfunction

    // ── VCD Dump ─────────────────────────────────────────────
    initial begin
        $dumpfile("dataset_sim.vcd");
        $dumpvars(0, alu_dataset_harness);
    end

    // ── Main stimulus ─────────────────────────────────────────
    initial begin
        clk = 0; rst = 1;
        A = 0; B = 0; opcode = 0;
        #20; rst = 0; #5;

        // Load stimulus files generated by Python
        $readmemh("stim_A.hex",     stim_A);
        $readmemh("stim_B.hex",     stim_B);
        $readmemh("stim_op.hex",    stim_op);
        $readmemh("stim_label.hex", stim_label);

        // Open CSV output
        fd = $fopen("raw_sim_output.csv", "w");
        $fwrite(fd, "cycle,A,B,opcode,label,");
        $fwrite(fd, "clean_result,clean_Z,clean_C,clean_V,clean_S,");
        $fwrite(fd, "t1_result,t1_Z,t1_C,t1_V,t1_S,");
        $fwrite(fd, "t2_result,t2_Z,t2_C,t2_V,t2_S,");
        $fwrite(fd, "t3_result,t3_Z,t3_C,t3_V,t3_S,t3_leakage,");
        $fwrite(fd, "clean_toggles,t1_toggles,t2_toggles,t3_toggles,leakage_toggles,flag_toggles\n");

        // Init toggle tracking
        prev_clean_result = 0; prev_t1_result = 0;
        prev_t2_result = 0;   prev_t3_result = 0;
        prev_leakage   = 0;   prev_flags     = 0;

        for (i = 0; i < NUM_CYCLES; i = i + 1) begin
            // Apply stimulus
            A      = stim_A[i];
            B      = stim_B[i];
            opcode = stim_op[i];

            @(posedge clk); #2; // Wait for combinational settle

            // Count bit toggles (switching activity proxy)
            clean_toggles   = popcount16(clean_result ^ prev_clean_result);
            t1_toggles      = popcount16(t1_result    ^ prev_t1_result);
            t2_toggles      = popcount16(t2_result    ^ prev_t2_result);
            t3_toggles      = popcount16(t3_result    ^ prev_t3_result);
            leakage_toggles = popcount8(t3_leakage    ^ prev_leakage);
            flag_toggles    = popcount4({clean_Z,clean_C,clean_V,clean_S} ^ prev_flags);

            // Write CSV row
            $fwrite(fd, "%0d,%0h,%0h,%0h,%0d,",
                    i, A, B, opcode, stim_label[i]);
            $fwrite(fd, "%0h,%0b,%0b,%0b,%0b,",
                    clean_result, clean_Z, clean_C, clean_V, clean_S);
            $fwrite(fd, "%0h,%0b,%0b,%0b,%0b,",
                    t1_result, t1_Z, t1_C, t1_V, t1_S);
            $fwrite(fd, "%0h,%0b,%0b,%0b,%0b,",
                    t2_result, t2_Z, t2_C, t2_V, t2_S);
            $fwrite(fd, "%0h,%0b,%0b,%0b,%0b,%0h,",
                    t3_result, t3_Z, t3_C, t3_V, t3_S, t3_leakage);
            $fwrite(fd, "%0d,%0d,%0d,%0d,%0d,%0d\n",
                    clean_toggles, t1_toggles, t2_toggles,
                    t3_toggles, leakage_toggles, flag_toggles);

            // Update previous values
            prev_clean_result = clean_result;
            prev_t1_result    = t1_result;
            prev_t2_result    = t2_result;
            prev_t3_result    = t3_result;
            prev_leakage      = t3_leakage;
            prev_flags        = {clean_Z, clean_C, clean_V, clean_S};
        end

        $fclose(fd);
        $display("[SIM] Dataset simulation complete. %0d cycles logged.", NUM_CYCLES);
        $finish;
    end

endmodule
